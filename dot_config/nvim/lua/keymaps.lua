-- [[ Basic Autocommands ]]
--  See `:help lua-guide-autocommands`

-- Highlight when yanking (copying) text
--  Try it with `yap` in normal mode
--  See `:help vim.hl.on_yank()`
vim.api.nvim_create_autocmd('TextYankPost', {
  desc = 'Highlight when yanking (copying) text',
  group = vim.api.nvim_create_augroup('kickstart-highlight-yank', { clear = true }),
  callback = function() vim.hl.on_yank() end,
})

-- Force transparent background after colorscheme loads.
-- Catppuccin sets transparent_background = true but some highlight groups
-- can still be overridden by other plugins.
local function set_transparent_background()
  local groups = { 'Normal', 'NormalNC', 'SignColumn', 'EndOfBuffer', 'LineNr', 'FoldColumn', 'NormalFloat', 'FloatBorder', 'FloatTitle' }
  for _, group in ipairs(groups) do
    local hl = vim.api.nvim_get_hl(0, { name = group, link = false })
    hl.bg = nil
    hl.ctermbg = nil
    vim.api.nvim_set_hl(0, group, hl)
  end
end
vim.api.nvim_create_autocmd('ColorScheme', { callback = set_transparent_background })
vim.api.nvim_create_autocmd('VimEnter', { once = true, callback = set_transparent_background })

